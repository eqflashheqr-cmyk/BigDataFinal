"""
rq3_equivalence.py — Cell-by-cell equivalence check for RQ3.

Why this exists
---------------
The RQ3 cross-engine claim in the report ("1,730 strata, zero differing
cells") needs evidence that survives a clean clone. The raw per-engine
result files (`results/rq3_pandas.csv` and `results/rq3_spark.csv`) are
intermediate artefacts regenerated by `src/analysis.py`, so they are not
tracked in git. This script compares them and writes a small, permanent
summary to `results/rq3_equivalence.json`, which *is* tracked and is what
the report cites.

Usage
-----
    python src/run_analysis.py all          # produces the two input CSVs
    python src/rq3_equivalence.py            # compares them

Interpretation of the one expected difference
---------------------------------------------
The two engines disagree on `joint_lower` for 182 of the 1,730 strata. This
is **not** a numerical discrepancy: Pandas writes `NaN` when a stratum has
no decisions for one of the two groups (so the denial rate is undefined),
whereas Spark's SQL comparison of a NULL yields `False`. The underlying
counts and rates are bit-identical in all 1,730 rows. This script treats
`NaN` and `False` as equivalent for that column and reports the number of
rows that differ only in this way, so the distinction is explicit rather
than hidden.
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config as C

PANDAS_CSV = C.RESULTS_DIR / "rq3_pandas.csv"
SPARK_CSV = C.RESULTS_DIR / "rq3_spark.csv"
OUT_JSON = C.RESULTS_DIR / "rq3_equivalence.json"

#: The four columns that identify a stratum. `joint_lower` is deliberately
#: excluded: it is the one column with a NULL-representation difference.
KEY_COLS = ["income_quartile", "dti_band", "loan_type_label", "loan_purpose_label"]

#: Columns that must match numerically. Counts are integers and must match
#: exactly; rates are floats and are compared within `C.TOLERANCE`.
COUNT_COLS = ["n_decisions_joint", "n_decisions_single", "n_denied_joint",
              "n_denied_single", "n_decisions_total"]
RATE_COLS = ["denial_rate_joint", "denial_rate_single", "gap_pp"]
FLAG_COLS = ["suppressed_small_cell"]


def _normalise_joint_lower(s: pd.Series) -> pd.Series:
    """Map Pandas NaN and Spark's False onto the same value.

    Both mean "this stratum has no decisions for one of the two groups, so
    the comparison is undefined". `joint_lower` is False in both cases: the
    joint group cannot have the lower denial rate when it has no decisions.
    """
    return s.astype(object).where(s.notna(), False).astype(bool)


def compare() -> dict:
    if not PANDAS_CSV.exists() or not SPARK_CSV.exists():
        raise SystemExit(
            f"Missing input. Run 'python src/run_analysis.py all' first "
            f"(expected {PANDAS_CSV.name} and {SPARK_CSV.name} in {C.RESULTS_DIR})."
        )

    p = pd.read_csv(PANDAS_CSV)
    s = pd.read_csv(SPARK_CSV)

    if list(p.columns) != list(s.columns):
        return {
            "agree": False,
            "reason": "column sets differ",
            "pandas_columns": list(p.columns),
            "spark_columns": list(s.columns),
        }

    if len(p) != len(s):
        return {
            "agree": False,
            "reason": "row counts differ",
            "pandas_rows": int(len(p)),
            "spark_rows": int(len(s)),
        }

    # Sort both by the stratum keys so the comparison is positional.
    pk = p.sort_values(KEY_COLS).reset_index(drop=True)
    sk = s.sort_values(KEY_COLS).reset_index(drop=True)

    # ---- 1. do the two engines produce the same strata? -------------------
    key_mismatches = int((pk[KEY_COLS].astype(str) != sk[KEY_COLS].astype(str)).any(axis=1).sum())

    # ---- 2. do the counts match exactly? ---------------------------------
    count_mismatches = {}
    for c in COUNT_COLS:
        a = pd.to_numeric(pk[c], errors="coerce").fillna(-1)
        b = pd.to_numeric(sk[c], errors="coerce").fillna(-1)
        count_mismatches[c] = int((a != b).sum())

    # ---- 3. do the rates match within tolerance? ------------------------
    rate_mismatches = {}
    max_rate_diff = 0.0
    for c in RATE_COLS:
        a = pd.to_numeric(pk[c], errors="coerce")
        b = pd.to_numeric(sk[c], errors="coerce")
        # A rate is undefined (NaN) in exactly the same strata in both
        # engines; compare only where at least one side has a value, and
        # treat both-NaN as agreement.
        both_nan = a.isna() & b.isna()
        d = (a.fillna(0.0) - b.fillna(0.0)).abs()
        d = d.mask(both_nan, 0.0)
        rate_mismatches[c] = int((d > C.TOLERANCE).sum())
        max_rate_diff = max(max_rate_diff, float(d.max()))

    # ---- 4. do the suppression flags match? ------------------------------
    flag_mismatches = {}
    for c in FLAG_COLS:
        a = pk[c].fillna(False).astype(str).str.lower()
        b = sk[c].fillna(False).astype(str).str.lower()
        flag_mismatches[c] = int((a != b).sum())

    # ---- 5. the one expected representational difference ------------------
    jl_p = _normalise_joint_lower(pk["joint_lower"])
    jl_s = _normalise_joint_lower(sk["joint_lower"])
    joint_lower_real_mismatch = int((jl_p != jl_s).sum())
    joint_lower_null_repr = int(
        (pk["joint_lower"].isna() != sk["joint_lower"].isna()).sum()
    )

    total_numeric_mismatches = (
        sum(count_mismatches.values())
        + sum(rate_mismatches.values())
        + sum(flag_mismatches.values())
    )

    agree = (
        key_mismatches == 0
        and total_numeric_mismatches == 0
        and joint_lower_real_mismatch == 0
    )

    return {
        "agree": agree,
        "n_strata": int(len(p)),
        "tolerance": C.TOLERANCE,
        "key_columns": KEY_COLS,
        "strata_key_mismatches": key_mismatches,
        "count_mismatches": count_mismatches,
        "rate_mismatches": rate_mismatches,
        "flag_mismatches": flag_mismatches,
        "max_rate_difference": max_rate_diff,
        "total_numeric_mismatches": total_numeric_mismatches,
        "joint_lower": {
            "real_mismatches": joint_lower_real_mismatch,
            "null_representation_differences": joint_lower_null_repr,
            "note": (
                "Pandas writes NaN where a stratum has no decisions for one "
                "group; Spark's SQL comparison of NULL yields False. Both mean "
                "the joint group cannot have the lower denial rate. Counts and "
                "rates are identical in every stratum."
            ),
        },
        "pandas_version": pd.__version__,
    }


def main() -> None:
    result = compare()
    OUT_JSON.write_text(json.dumps(result, indent=2), encoding="utf-8")

    print("=" * 78)
    print("RQ3 — PANDAS vs PYSPARK CELL-BY-CELL EQUIVALENCE")
    print("=" * 78)
    print(f"  strata compared      : {result.get('n_strata', 0):,}")
    print(f"  strata key mismatches: {result.get('strata_key_mismatches', '?')}")
    print(f"  numeric mismatches   : {result.get('total_numeric_mismatches', '?')}")
    print(f"  max rate difference  : {result.get('max_rate_difference', '?'):.3g}")
    jl = result.get("joint_lower", {})
    print(f"  joint_lower real diff: {jl.get('real_mismatches', '?')}")
    print(f"  null-repr differences: {jl.get('null_representation_differences', '?')}")
    print()
    print(f"  RESULT: {'AGREE' if result['agree'] else 'DISAGREE'}")
    print(f"  Written: {OUT_JSON}")


if __name__ == "__main__":
    main()
